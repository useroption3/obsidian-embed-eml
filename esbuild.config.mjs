import esbuild from "esbuild";
import process from "process";
import { readFileSync } from "fs";
import { builtinModules } from "module";

const { version } = JSON.parse(readFileSync("manifest.json", "utf8"));

// The version keeps main.js unique per release: GitHub keys attestations by file
// digest, and an unchanged digest keeps serving the previous release's attestation.
const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
Embed EML ${version}
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === "production";

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ["src/main.ts"],
	bundle: true,
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtinModules,
	],
	format: "cjs",
	target: "es2018",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	outfile: "main.js",
	minify: prod,
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
